// Helper functions
export function getServiceBySlug(slug) {
  return servicesData.find(service => service.slug === slug);
}

export function getRelatedServices(slug, count = 3) {
  const current = getServiceBySlug(slug);
  if (!current) return [];
  return servicesData
    .filter(s => s.id !== current.id)
    .slice(0, count);
}